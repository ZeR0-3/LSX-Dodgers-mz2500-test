#!/usr/bin/env python3
"""MZ-2500 キーマトリクス(列O0-O13 x 行D7..D0) -> KEY/SHIFT/CTRL テーブル
資料: MZ-2500 ユーザーズマニュアル p.182 / MZ2500_IO_Map の PIO E8h/EAh 節
各列8バイト、D7からD0の順。0=未割当(無視)。"""
import sys
Z = (0,0,0)
def k(n, s=None, c=None):
    if isinstance(n,str): n = ord(n)
    if s is None: s = n
    if isinstance(s,str): s = ord(s)
    if c is None: c = n
    if isinstance(c,str): c = ord(c)
    return (n,s,c)
def L(ch):
    o = ord(ch.lower()); return (o, ord(ch.upper()), o-0x60)
cols = {}
cols[0]  = [Z]*8                                              # F8..F1
cols[1]  = [k('-'),k('+'),k('.'),k(','),k('9'),k('8'),Z,Z]    # テンキー - + . , 9 8 / F10 F9
cols[2]  = [k(c) for c in '76543210']                         # テンキー 7..0
cols[3]  = [Z,k(0x1C),k(0x1D),k(0x1F),k(0x1E),k(0x0D),k(0x20),k(0x09)]  # BREAK → ← ↓ ↑ CR SPACE TAB
cols[4]  = [L('g'),L('f'),L('e'),L('d'),L('c'),L('b'),L('a'),k('/','?')]
cols[5]  = [L('o'),L('n'),L('m'),L('l'),L('k'),L('j'),L('i'),L('h')]
cols[6]  = [L('w'),L('v'),L('u'),L('t'),L('s'),L('r'),L('q'),L('p')]
cols[7]  = [k(',','<'),k('.','>'),k(0x5C,'_'),k(0x5C,'|'),k('^','~'),L('z'),L('y'),L('x')]
cols[8]  = [k('7',0x27),k('6','&'),k('5','%'),k('4','$'),k('3','#'),k('2','"'),k('1','!'),k('0')]
cols[9]  = [Z,k('[','{',0x1B),k('@','`'),k('-','='),k(';','+'),k(':','*'),k('9',')'),k('8','(')]
cols[10] = [k('/'),k('*'),k(0x1B),k(0x08),k(0x12),k(0x0B,0x0C),Z,k(']','}')]  # / * ESC BS INST/DEL CLR/HOME COPY ]
cols[11] = [Z]*8   # CTRL KANA SHIFT LOCK GRAPH (モディファイア)
cols[12] = [Z]*8   # 変換 無変換
cols[13] = [Z]*8   # HELP
# カナ配列(JIS配列): (通常, SHIFT)  コードは JIS X 0201 半角カナ
def K(a, b=None): return (a, a if b is None else b)
KA = {  # (列,行D7=0..D0=7) -> (通常カナ, SHIFTカナ)
 (4,0):K(0xB7),(4,1):K(0xCA),(4,2):K(0xB2,0xA8),(4,3):K(0xBC),(4,4):K(0xBF),(4,5):K(0xBA),(4,6):K(0xC1),(4,7):K(0xD2,0xA5),
 (5,0):K(0xD7),(5,1):K(0xD0),(5,2):K(0xD3),(5,3):K(0xD8),(5,4):K(0xC9),(5,5):K(0xCF),(5,6):K(0xC6),(5,7):K(0xB8),
 (6,0):K(0xC3),(6,1):K(0xCB),(6,2):K(0xC5),(6,3):K(0xB6),(6,4):K(0xC4),(6,5):K(0xBD),(6,6):K(0xC0),(6,7):K(0xBE),
 (7,0):K(0xC8,0xA4),(7,1):K(0xD9,0xA1),(7,2):K(0xDB),(7,3):K(0xB0),(7,4):K(0xCD),(7,5):K(0xC2,0xAF),(7,6):K(0xDD),(7,7):K(0xBB),
 (8,0):K(0xD4,0xAC),(8,1):K(0xB5,0xAB),(8,2):K(0xB4,0xAA),(8,3):K(0xB3,0xA9),(8,4):K(0xB1,0xA7),(8,5):K(0xCC),(8,6):K(0xC7),(8,7):K(0xDC,0xA6),
 (9,1):K(0xDF,0xA2),(9,2):K(0xDE),(9,3):K(0xCE),(9,4):K(0xDA),(9,5):K(0xB9),(9,6):K(0xD6,0xAE),(9,7):K(0xD5,0xAD),
 (10,7):K(0xD1,0xA3),
}
def kana_table(idx):
    t = {}
    for c in range(14):
        for r in range(8): t[(c,r)] = cols[c][r][0]
    for (c,r),v in KA.items(): t[(c,r)] = v[idx]
    return t
# 元の表の並びは「ビット D7..D0」= 添字0..7。上の KA の行番号も D7=0..D0=7
out = ["", ";\tLSX-Dodgers TABLE キー表", ";\tMZ-2500 (generated by tools/gen_m25table.py)", ""]
out += ["AT_TABLE:", "\tDS\tTABLEAD-AT_TABLE", ""]
for idx, name in enumerate(('KEY_TABLE','SHIFT_TABLE','CTRL_TABLE')):
    out.append(name + ':')
    for c in range(14):
        out.append('\tDB\t' + ','.join('%03XH' % cols[c][r][idx] if False else '0%02XH' % cols[c][r][idx] for r in range(8)) + '\t;列%d' % c)
for name, kt in (('KANA_TABLE', kana_table(0)), ('KSHIFT_TABLE', kana_table(1))):
    out.append(name + ':')
    for c in range(14):
        out.append('\tDB\t' + ','.join('0%02XH' % kt[(c,r)] for r in range(8)) + '\t;列%d' % c)
open(sys.argv[1], 'w', encoding='utf-8').write('\n'.join(out) + '\n')
