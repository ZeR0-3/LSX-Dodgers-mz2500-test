DEV	EQU	0

VER_6F	EQU	0011DH

RUN	EQU	04100H		;IPLヘッダ(レコード0, 256バイト)の直後
OFFSET	EQU	RUN-256
BDOS	EQU	0CF06H
WORKAD	EQU	0F000H
TABLEAD	EQU	0EDD0H	;キー表5枚(112B x5=560B)が WORKAD(0F000H) 直前に収まる位置(AT_WORKの詰め物を無くして本体の空きを増やした)
KEYBF	EQU	0F300H
FATBF	EQU	0F330H
DTBUF	EQU	0FB30H
KBUF	EQU	0FF30H
TRAP38	EQU	0FFD9H
#IF EXISTS COLS80
WIDTH	EQU	80		;80桁(IOCS TINITで切替)
#ELSE
WIDTH	EQU	40		;ブート時の40桁のまま使う
#ENDIF
LINE	EQU	25
COLORF	EQU	007H		;テキスト属性(白) bit2:G bit1:R bit0:B
KEYSP_H	EQU	20
KEYSP_L	EQU	131
COMS	EQU	9
MAX_SEC_SZ_H	EQU	4	;1セクタ1024バイトのサポート(2:off 4:on)
BUFFER	EQU	00100H

